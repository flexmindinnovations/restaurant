#!/usr/bin/env node
// Generates platform token files from the canonical DTCG JSON in ../src.
//   node scripts/build.mjs           write outputs
//   node scripts/build.mjs --check   exit 1 if any committed output is stale
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { buildModel, PKG_ROOT, THEMES, DEFAULT_THEME, toCssColor, toHex, toArgbInt } from './lib.mjs';

const CHECK = process.argv.includes('--check');
const REPO = join(PKG_ROOT, '..', '..');
const DIST = join(PKG_ROOT, 'dist');
const DART_OUT = join(REPO, 'packages', 'flutter-ui', 'lib', 'src', 'tokens', 'dosa_tokens.g.dart');
const HEADER = 'DO NOT EDIT. Generated by packages/design-tokens/scripts/build.mjs from packages/design-tokens/src.';

const model = buildModel();
const files = new Map();
const emit = (path, content) => files.set(path, content.endsWith('\n') ? content : content + '\n');

// ---------------- naming ----------------
const kebab = (path) => path.join('-');
const cssVar = (path) => `--dosa-${kebab(path)}`;
const camel = (path) => path
  .map((p) => p.replace(/-5$/, 'Half'))
  .join('-')
  .split(/[-.]/)
  .filter(Boolean)
  .map((s, i) => (i === 0 ? s : s[0].toUpperCase() + s.slice(1)))
  .join('');

// ---------------- CSS values ----------------
const fontStack = (arr) => arr.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ');

function cssValue(tok) {
  const v = tok.value;
  switch (tok.type) {
    case 'color': return tok.directRef ? `var(${cssVar(tok.directRef.split('.'))})` : toCssColor(v);
    case 'fontFamily': return fontStack(v);
    case 'cubicBezier': return `cubic-bezier(${v.join(', ')})`;
    case 'shadow': return v.length ? v.map((s) => `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${toCssColor(s.color)}`).join(', ') : 'none';
    case 'gradient': {
      const angle = tok.ext['dosa.angle'] ?? 135;
      return `linear-gradient(${angle}deg, ${v.map((s) => `${toCssColor(s.color)} ${+(s.position * 100).toFixed(2)}%`).join(', ')})`;
    }
    default: return String(v);
  }
}

function cssDecls(tok) {
  if (tok.type === 'typography') {
    const v = tok.value; const base = cssVar(tok.path);
    return [
      [`${base}-font-family`, fontStack(v.fontFamily)],
      [`${base}-font-weight`, String(v.fontWeight)],
      [`${base}-font-size`, v.fontSize],
      [`${base}-line-height`, String(v.lineHeight)],
      [`${base}-letter-spacing`, v.letterSpacing],
      [`${base}`, `${v.fontWeight} ${v.fontSize}/${v.lineHeight} ${fontStack(v.fontFamily)}`],
    ];
  }
  return [[cssVar(tok.path), cssValue(tok)]];
}

const block = (selector, toks, extra = []) => `${selector} {\n${[...extra, ...[...toks.values()].flatMap(cssDecls).map(([k, v]) => `${k}: ${v};`)].map((l) => `  ${l}`).join('\n')}\n}`;

// ---------------- CSS ----------------
{
  const { primitives, themes } = model;
  const parts = [`/* ${HEADER} */`, '', '/* Primitives + foundations. Application code should not use --dosa-color-<hue>-<step> directly. */'];
  parts.push(block(':root', primitives));
  parts.push('', `/* Default theme: ${DEFAULT_THEME}. */`);
  parts.push(block(`:root,\n[data-dosa-theme="${DEFAULT_THEME}"]`, themes[DEFAULT_THEME].tokens, [`color-scheme: ${themes[DEFAULT_THEME].scheme};`]));
  for (const name of THEMES.filter((t) => t !== DEFAULT_THEME)) {
    parts.push('', `/* ${themes[name].description} */`);
    parts.push(block(`[data-dosa-theme="${name}"]`, themes[name].tokens, [`color-scheme: ${themes[name].scheme};`]));
  }
  emit(join(DIST, 'css', 'tokens.css'), parts.join('\n'));
}

// ---------------- SCSS ----------------
{
  const { primitives, themes } = model;
  const lines = [`// ${HEADER}`, '// Each variable points at the runtime CSS custom property, so themes switch at runtime.', '// Use $dosa-palette only where Sass needs a literal colour (e.g. Angular Material palette generation).', ''];
  const names = new Set();
  for (const t of [...primitives.values(), ...themes[DEFAULT_THEME].tokens.values()]) {
    for (const [k] of cssDecls(t)) names.add(k);
  }
  for (const k of names) lines.push(`$${k.slice(2)}: var(${k});`);
  lines.push('', '$dosa-palette: (');
  for (const t of primitives.values()) if (t.type === 'color') lines.push(`  '${kebab(t.path.slice(1))}': ${toHex(t.value)},`);
  lines.push(');', '', '$dosa-breakpoints: (');
  for (const t of primitives.values()) if (t.path[0] === 'breakpoint') lines.push(`  '${t.path[1]}': ${t.value},`);
  lines.push(');');
  emit(join(DIST, 'scss', '_tokens.scss'), lines.join('\n'));
}

// ---------------- JSON + TS ----------------
const jsonValue = (t) => {
  switch (t.type) {
    case 'color': return toCssColor(t.value);
    case 'shadow': return t.value.map((s) => ({ ...s, color: toCssColor(s.color) }));
    case 'gradient': return { angle: t.ext['dosa.angle'] ?? 135, stops: t.value.map((s) => ({ color: toCssColor(s.color), position: s.position })) };
    case 'typography': return { ...t.value };
    default: return t.value;
  }
};
{
  const { primitives, themes } = model;
  const prim = Object.fromEntries([...primitives.values()].map((t) => [t.path.join('.'), jsonValue(t)]));
  emit(join(DIST, 'json', 'primitives.json'), JSON.stringify(prim, null, 2));
  const themeObjs = {};
  for (const name of THEMES) {
    themeObjs[name] = Object.fromEntries([...themes[name].tokens.values()].map((t) => [t.path.join('.'), jsonValue(t)]));
    emit(join(DIST, 'json', `${name}.json`), JSON.stringify(themeObjs[name], null, 2));
  }
  const ts = [
    `// ${HEADER}`,
    '/* eslint-disable */',
    `export const DOSA_THEMES = ${JSON.stringify(THEMES)} as const;`,
    'export type DosaThemeName = (typeof DOSA_THEMES)[number];',
    `export const DOSA_DEFAULT_THEME: DosaThemeName = '${DEFAULT_THEME}';`,
    `export const DOSA_THEME_SCHEME: Record<DosaThemeName, 'light' | 'dark'> = ${JSON.stringify(Object.fromEntries(THEMES.map((n) => [n, themes[n].scheme])))};`,
    '',
    `export const primitives = ${JSON.stringify(prim, null, 2)} as const;`,
    'export type DosaPrimitiveName = keyof typeof primitives;',
    '',
    `export const themes = ${JSON.stringify(themeObjs, null, 2)} as const;`,
    `export type DosaSemanticName = keyof (typeof themes)['${DEFAULT_THEME}'];`,
    '',
    '/** CSS custom property name for a token, e.g. cssVar("color.text.primary") → "var(--dosa-color-text-primary)". */',
    'export function cssVar(name: DosaSemanticName | DosaPrimitiveName): string {',
    "  return `var(--dosa-${name.replace(/\\./g, '-')})`;",
    '}',
  ];
  emit(join(DIST, 'ts', 'tokens.ts'), ts.join('\n'));
}

// ---------------- Dart ----------------
{
  const { primitives, themes } = model;
  const px = (s) => +String(s).replace('px', '');
  const ms = (s) => +String(s).replace('ms', '');
  const num = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
  const color = (c) => `Color(${toArgbInt(c)})`;
  const shadows = (v) => `<BoxShadow>[${v.map((s) => `BoxShadow(color: ${color(s.color)}, offset: Offset(${num(px(s.offsetX))}, ${num(px(s.offsetY))}), blurRadius: ${num(px(s.blur))}, spreadRadius: ${num(px(s.spread))})`).join(', ')}]`;
  const gradient = (t) => {
    const angle = t.ext['dosa.angle'] ?? 135;
    const rad = ((angle - 90) * Math.PI) / 180;
    return `LinearGradient(colors: <Color>[${t.value.map((s) => color(s.color)).join(', ')}], stops: <double>[${t.value.map((s) => num(s.position)).join(', ')}], transform: GradientRotation(${rad.toFixed(6)}))`;
  };
  const familyName = (arr) => (arr[0] === 'Plus Jakarta Sans' ? 'PlusJakartaSans' : arr[0] === 'Inter' ? 'Inter' : null);
  const textStyle = (t) => {
    const v = t.value; const fam = familyName(v.fontFamily);
    const size = px(v.fontSize); const ls = +(parseFloat(v.letterSpacing) * size).toFixed(3);
    const feats = t.path[1] === 'numeric' ? ', fontFeatures: <FontFeature>[FontFeature.tabularFigures()]' : '';
    const vars = [`FontVariation('wght', ${num(v.fontWeight)})`];
    if (fam === 'Inter') vars.push(`FontVariation('opsz', ${num(Math.min(32, Math.max(14, size)))})`);
    return `TextStyle(${fam ? `fontFamily: '${fam}', package: 'dosa_ui', ` : ''}fontWeight: FontWeight.w${v.fontWeight}, fontVariations: <FontVariation>[${vars.join(', ')}], fontSize: ${num(size)}, height: ${v.lineHeight}, letterSpacing: ${ls}${feats})`;
  };
  const doc = (t) => (t.description ? `  /// ${t.description.replace(/\n/g, ' ')}\n` : '');
  const out = [
    `// ${HEADER}`,
    '// ignore_for_file: public_member_api_docs, constant_identifier_names',
    '',
        "import 'package:flutter/animation.dart' show Cubic;",
    "import 'package:flutter/painting.dart';",
    '',
  ];
  const group = (cls, doc0, filter, render, type, prefix = 'v', depth = 1) => {
    out.push(`/// ${doc0}`, `abstract final class ${cls} {`);
    for (const t of primitives.values()) if (filter(t)) { let id = camel(t.path.slice(depth)) || 'value'; if (/^\d/.test(id)) id = prefix + id; out.push(`${doc(t)}  static const ${type} ${id} = ${render(t)};`); }
    out.push('}', '');
  };
  group('DosaPalette', 'Primitive palette. Prefer [DosaThemeTokens] semantic colours in widgets.', (t) => t.type === 'color', (t) => color(t.value), 'Color');
  group('DosaSpace', '4px spacing scale (logical pixels).', (t) => t.path[0] === 'space', (t) => num(px(t.value)), 'double', 's');
  group('DosaRadius', 'Corner radii (logical pixels).', (t) => t.path[0] === 'radius', (t) => num(Math.min(px(t.value), 999)), 'double');
  group('DosaSize', 'Control, touch target and icon sizes.', (t) => t.path[0] === 'size' && t.type === 'dimension', (t) => num(px(t.value)), 'double');
  group('DosaBorderWidth', 'Border and focus-ring widths (logical pixels).', (t) => t.path[0] === 'border' && t.path[1] === 'width', (t) => num(px(t.value)), 'double', 'w', 2);
  group('DosaIconStroke', 'Stroke widths for Lucide-style icons.', (t) => t.path[0] === 'size' && t.path[1] === 'icon-stroke', (t) => num(t.value), 'double');
  group('DosaOpacity', 'Opacity constants.', (t) => t.path[0] === 'opacity', (t) => num(t.value), 'double');
  group('DosaBreakpoint', 'Layout breakpoints (logical pixels).', (t) => t.path[0] === 'breakpoint', (t) => num(px(t.value)), 'double', 'bp');
  group('DosaDuration', 'Motion durations.', (t) => t.path[1] === 'duration', (t) => `Duration(milliseconds: ${ms(t.value)})`, 'Duration', 'v', 2);
  group('DosaEasing', 'Motion easing curves.', (t) => t.path[1] === 'easing', (t) => `Cubic(${t.value.map(num).join(', ')})`, 'Cubic', 'v', 2);
  group('DosaTypeScale', 'Type scale. Numeric styles carry tabular figures.', (t) => t.type === 'typography', textStyle, 'TextStyle');

  // Theme tokens class
  const sample = [...themes[DEFAULT_THEME].tokens.values()];
  const dartType = (t) => ({ color: 'Color', shadow: 'List<BoxShadow>', gradient: 'LinearGradient', dimension: 'double', number: 'double', string: 'String' }[t.type]);
  const dartVal = (t) => {
    switch (t.type) {
      case 'color': return color(t.value);
      case 'shadow': return shadows(t.value);
      case 'gradient': return gradient(t);
      case 'dimension': return num(px(t.value));
      case 'number': return num(+t.value);
      case 'string': return `'${t.value}'`;
      default: throw new Error(`No Dart mapping for ${t.type} (${t.path.join('.')})`);
    }
  };
  const shortName = (t) => camel(t.path[0] === 'color' ? t.path.slice(1) : t.path);
  const shortCounts = new Map();
  for (const t of sample) shortCounts.set(shortName(t), (shortCounts.get(shortName(t)) ?? 0) + 1);
  // Colour tokens drop the "color" prefix unless that would collide (e.g. color.shadow.brand vs shadow.brand).
  const field = (t) => (shortCounts.get(shortName(t)) > 1 && t.path[0] === 'color' ? camel(t.path) : shortName(t));
  out.push('/// Semantic tokens for one DOSA theme. Identical keys across every theme.', 'final class DosaThemeTokens {', '  const DosaThemeTokens({', '    required this.name,', '    required this.isDark,');
  for (const t of sample) out.push(`    required this.${field(t)},`);
  out.push('  });', '', '  final String name;', '  final bool isDark;');
  for (const t of sample) out.push(`${doc(t)}  final ${dartType(t)} ${field(t)};`);
  out.push('');
  for (const name of THEMES) {
    out.push(`  static const DosaThemeTokens ${camel([name])} = DosaThemeTokens(`, `    name: '${name}',`, `    isDark: ${themes[name].scheme === 'dark'},`);
    for (const t of themes[name].tokens.values()) out.push(`    ${field(t)}: ${dartVal(t)},`);
    out.push('  );', '');
  }
  out.push(`  static const List<DosaThemeTokens> all = <DosaThemeTokens>[${THEMES.map((n) => camel([n])).join(', ')}];`, '}');
  emit(DART_OUT, out.join('\n'));
}

// ---------------- Markdown reference (docs/reference/TOKEN_REFERENCE.md) ----------------
{
  const { primitives, themes } = model;
  const P = Object.fromEntries([...primitives.values()].map((t) => [t.path.join('.'), t]));
  const md = [`<!-- ${HEADER} -->`, '', '# DOSA token reference', '', 'Every value below is generated from `packages/design-tokens/src`. CSS custom property = `--dosa-` + token path with dots replaced by dashes.', ''];
  const tbl = (head, rows) => { md.push(`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`); for (const r of rows) md.push(`| ${r.join(' | ')} |`); md.push(''); };
  const cell = (v) => `\`${v}\``;
  md.push('## Primitive colours', '');
  tbl(['Token', 'Value', 'Notes'], [...primitives.values()].filter((t) => t.type === 'color').map((t) => [cell(t.path.join('.')), cell(toCssColor(t.value)), t.description.replace(/\|/g, '/')]));
  md.push('## Typography', '');
  tbl(['Token', 'Family', 'Weight', 'Size', 'Line height', 'Tracking', 'Use'], [...primitives.values()].filter((t) => t.type === 'typography').map((t) => {
    const v = t.value; const lh = Math.round(parseFloat(v.fontSize) * v.lineHeight);
    return [cell(t.path.join('.')), v.fontFamily[0], v.fontWeight, v.fontSize, `${lh}px (${v.lineHeight})`, v.letterSpacing, t.description.replace(/\|/g, '/')];
  }));
  for (const [title, pre] of [['Spacing', 'space.'], ['Radius', 'radius.'], ['Border & focus', 'border.'], ['Focus ring', 'focus.'], ['Opacity', 'opacity.'], ['Sizes', 'size.'], ['Breakpoints', 'breakpoint.'], ['Grid', 'grid.'], ['Z-index', 'z.'], ['Motion', 'motion.'], ['Font features', 'font.feature.']]) {
    md.push(`## ${title}`, '');
    tbl(['Token', 'Value', 'Notes'], Object.values(P).filter((t) => t.path.join('.').startsWith(pre)).map((t) => [cell(t.path.join('.')), cell(cssValue(t).replace(/\|/g, '/')), t.description.replace(/\|/g, '/')]));
  }
  md.push('## Semantic tokens by theme', '', 'Colours shown resolved. Alpha values use `rgb(r g b / a)`.', '');
  const names = [...themes[DEFAULT_THEME].tokens.keys()];
  const show = (t) => {
    if (t.type === 'color') return cell(toCssColor(t.value));
    if (t.type === 'shadow') return t.value.length ? `${t.value.length}-layer` : 'none';
    if (t.type === 'gradient') return t.value.map((s) => cell(toCssColor(s.color))).join(' → ');
    return cell(String(t.value));
  };
  tbl(['Token', ...THEMES], names.map((n) => [cell(n), ...THEMES.map((th) => show(themes[th].tokens.get(n)))]));
  emit(join(REPO, 'docs', 'reference', 'TOKEN_REFERENCE.md'), md.join('\n'));
}

// ---------------- write / check ----------------
let stale = 0;
for (const [path, content] of files) {
  const rel = relative(REPO, path);
  if (CHECK) {
    const cur = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (cur !== content) { stale++; console.error(`stale: ${rel}`); }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${rel}`);
  }
}
if (CHECK) {
  if (stale) { console.error(`\n${stale} generated file(s) are out of date. Run: pnpm tokens:build`); process.exit(1); }
  console.log(`All ${files.size} generated token files are up to date.`);
}
