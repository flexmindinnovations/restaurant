#!/usr/bin/env node
// Bundles DOSA web foundations into dist/dosa.css and copies fonts/textures beside it.
// Also verifies that every var(--dosa-*) used by the layer files exists in the token CSS.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PKGS = join(ROOT, '..');
const DIST = join(ROOT, 'dist');
const tokensCss = readFileSync(join(PKGS, 'design-tokens', 'dist', 'css', 'tokens.css'), 'utf8');
const LAYERS = ['fonts.css', 'base.css', 'type.css', 'surfaces.css', 'gradients.css', '../../motion-assets/css/dosa-motion.css'];

const defined = new Set([...tokensCss.matchAll(/(--dosa-[a-z0-9-]+)\s*:/g)].map((m) => m[1]));
let missing = 0;
const parts = ['/* DOSA web foundations. Generated by packages/web-ui/scripts/build.mjs. */', '@layer dosa.tokens, dosa.base, dosa.surfaces, dosa.utilities;', '@layer dosa.tokens {', tokensCss, '}'];
for (const f of LAYERS) {
  const css = readFileSync(join(ROOT, 'src', f), 'utf8');
  for (const [, name] of css.matchAll(/var\((--dosa-[a-z0-9-]+)/g)) {
    if (!defined.has(name) && !name.startsWith('--dosa-mesh-')) { missing++; console.error(`✗ ${f}: ${name} is not a token`); }
  }
  parts.push(`/* ---- ${f} ---- */`, css);
}
if (missing) process.exit(1);

rmSync(DIST, { recursive: true, force: true });
mkdirSync(join(DIST, 'assets', 'fonts'), { recursive: true });
mkdirSync(join(DIST, 'assets', 'textures'), { recursive: true });
writeFileSync(join(DIST, 'dosa.css'), parts.join('\n'));
const BA = join(PKGS, 'brand-assets');
for (const f of ['inter/InterVariable-latin.woff2', 'plus-jakarta-sans/PlusJakartaSansVariable-latin.woff2']) copyFileSync(join(BA, 'fonts', f), join(DIST, 'assets', 'fonts', f.split('/')[1]));
for (const f of ['paper-grain-256.webp', 'paper-grain-256.png', 'paper-grain-ink-256.webp', 'paper-grain-pearl-256.webp']) copyFileSync(join(BA, 'textures', f), join(DIST, 'assets', 'textures', f));
console.log(`dist/dosa.css written (${defined.size} tokens, ${LAYERS.length} layers); fonts and textures copied.`);
